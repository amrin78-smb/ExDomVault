const { monthlyReports } = schema;

/**
 * Monthly executive report (Milestone 14; contract in packages/shared/src/api/monthly-report.ts).
 * Generated by a fixed set of aggregate statements over findings, status history, inventory, TLS
 * observations and score snapshots, then stored unchanged (`monthly_reports.data`).
 */

const DAY_MS = 86_400_000;
const CERT_LOOKBACK_DAYS = 90;
const CERT_AHEAD_DAYS = 30;
const TOP = 10;
const BEST_WORST = 5;

async function rowsOf<T>(db: Database, query: SQL): Promise<T[]> {
  const res = (await db.execute(query)) as unknown as { rows: T[] };
  return res.rows;
}

const ts = (d: Date) => sql`${d.toISOString()}::timestamptz`;
const iso = (v: Date | string) => (v instanceof Date ? v : new Date(v)).toISOString();
const round1 = (n: number) => Math.round(n * 10) / 10;
const round2 = (n: number) => Math.round(n * 100) / 100;
const zeros = () => Object.fromEntries(SEVERITIES.map((s) => [s, 0])) as Record<Severity, number>;
const dayOf = (d: Date) => d.toISOString().slice(0, 10);
const periodDate = (p: MonthlyPeriod) => `${p}-01`;

/**
 * Status of every finding at `end`: its latest status-history entry before `end` (findings first
 * detected later have no entry and are absent).
 */
const statusAtEnd = (end: Date) => sql`(
  select distinct on (h.finding_id) h.finding_id, h.to_status
  from finding_status_history h
  where h.created_at < ${ts(end)}
  order by h.finding_id, h.created_at desc, h.id desc
)`;

/** Builds the report for `period` from the current database (no writes). */
export async function buildMonthlyReport(
  db: Database,
  period: MonthlyPeriod,
  now: Date,
): Promise<MonthlyReport> {
  const { start, end } = monthBounds(period);
  const prev = monthBounds(previousPeriod(start));

  const [totals] = await rowsOf<{
    domains: number;
    monitored: number;
    assets: number;
    approved: number;
    new_assets: number;
  }>(
    db,
    sql`select
      (select count(*) from domains where created_at < ${ts(end)})::int as domains,
      (select count(*) from domains where created_at < ${ts(end)} and monitoring_enabled)::int as monitored,
      (select count(*) from assets where created_at < ${ts(end)})::int as assets,
      (select count(*) from assets where created_at < ${ts(end)}
         and verification_status = 'approved')::int as approved,
      (select count(*) from assets where created_at >= ${ts(start)}
         and created_at < ${ts(end)})::int as new_assets`,
  );

  const opened = await rowsOf<{ severity: Severity; n: number }>(
    db,
    sql`select f.severity, count(*)::int as n from findings f
        where f.first_seen_at >= ${ts(start)} and f.first_seen_at < ${ts(end)}
        group by 1`,
  );
  const [reopened] = await rowsOf<{ n: number }>(
    db,
    sql`select count(*)::int as n from finding_status_history h
        where h.reason = 'recurrence' and h.created_at >= ${ts(start)} and h.created_at < ${ts(end)}`,
  );
  const resolved = await rowsOf<{ severity: Severity; n: number }>(
    db,
    sql`select f.severity, count(distinct f.id)::int as n
        from finding_status_history h join findings f on f.id = h.finding_id
        where h.to_status = 'resolved' and h.created_at >= ${ts(start)} and h.created_at < ${ts(end)}
        group by 1`,
  );

  const openAtEnd = await rowsOf<{
    severity: Severity;
    n: number;
    accepted: number;
    overdue: number;
    eol: number;
    kev: number;
  }>(
    db,
    sql`select f.severity, count(*)::int as n,
               (count(*) filter (where e.to_status = 'accepted_risk'))::int as accepted,
               (count(*) filter (where e.to_status <> 'accepted_risk'
                  and f.due_at is not null and f.due_at < ${ts(end)}))::int as overdue,
               (count(*) filter (where f.rule_id = 'SOFT-001'))::int as eol,
               (count(*) filter (where f.rule_id = 'SOFT-002'))::int as kev
        from ${statusAtEnd(end)} e join findings f on f.id = e.finding_id
        where e.to_status <> 'resolved'
        group by 1`,
  );

  const sla = await rowsOf<{
    severity: Severity;
    n: number;
    with_sla: number;
    within: number;
    days: number | null;
  }>(
    db,
    sql`select f.severity, count(*)::int as n,
               (count(*) filter (where f.due_at is not null))::int as with_sla,
               (count(*) filter (where f.due_at is not null and f.resolved_at <= f.due_at))::int as within,
               avg(extract(epoch from (f.resolved_at - f.first_seen_at)))::float8 / 86400 as days
        from findings f
        where f.status = 'resolved' and f.resolved_at >= ${ts(start)} and f.resolved_at < ${ts(end)}
        group by 1`,
  );

  const topFindings = await rowsOf<{
    id: string;
    rule_id: string;
    title: string;
    severity: Severity;
    risk_score: number;
    domain_id: string;
    fqdn: string;
    hostname: string;
    first_seen_at: Date | string;
    due_at: Date | string | null;
    accepted: boolean;
  }>(
    db,
    sql`select f.id, f.rule_id, f.title, f.severity, f.risk_score, f.domain_id, d.fqdn, f.hostname,
               f.first_seen_at, f.due_at, (e.to_status = 'accepted_risk') as accepted
        from ${statusAtEnd(end)} e
        join findings f on f.id = e.finding_id
        join domains d on d.id = f.domain_id
        where e.to_status <> 'resolved'
        order by f.risk_score desc, f.severity desc, f.first_seen_at, f.id
        limit ${TOP}`,
  );

  const topDomains = await rowsOf<{
    id: string;
    fqdn: string;
    criticality: Criticality;
    business_owner: string | null;
    open: number;
    risk: number;
    highest: Severity;
    grade: string | null;
  }>(
    db,
    sql`select d.id, d.fqdn, d.criticality, d.business_owner, count(*)::int as open,
               sum(f.risk_score)::int as risk, max(f.severity) as highest,
               (select s.grade from domain_score_snapshots s
                where s.domain_id = d.id and s.day < ${dayOf(end)}::date
                order by s.day desc limit 1) as grade
        from ${statusAtEnd(end)} e
        join findings f on f.id = e.finding_id
        join domains d on d.id = f.domain_id
        where e.to_status <> 'resolved'
        group by d.id
        order by risk desc, open desc, d.fqdn
        limit ${TOP}`,
  );

  // Latest snapshot per domain within a month (end-of-month score).
  const monthScores = (from: Date, to: Date) => sql`(
    select distinct on (s.domain_id) s.domain_id, s.score, s.grade
    from domain_score_snapshots s
    where s.day >= ${dayOf(from)}::date and s.day < ${dayOf(to)}::date
    order by s.domain_id, s.day desc
  )`;
  const scores = await rowsOf<{ id: string; fqdn: string; score: number; grade: string }>(
    db,
    sql`select d.id, d.fqdn, m.score, m.grade
        from ${monthScores(start, end)} m join domains d on d.id = m.domain_id
        order by m.score desc, d.fqdn`,
  );
  const [prevAvg] = await rowsOf<{ avg: number | null }>(
    db,
    sql`select avg(m.score)::float8 as avg from ${monthScores(prev.start, prev.end)} m`,
  );

  const [certs] = await rowsOf<{ n: number }>(
    db,
    sql`select count(*)::int as n from (
          select distinct on (t.hostname) t.hostname, t.not_after
          from tls_observations t
          where t.result_status = 'success'
            and t.observed_at >= ${ts(new Date(end.getTime() - CERT_LOOKBACK_DAYS * DAY_MS))}
            and t.observed_at < ${ts(end)}
          order by t.hostname, t.observed_at desc, t.id desc
        ) latest
        where latest.not_after is not null
          and latest.not_after <= ${ts(new Date(end.getTime() + CERT_AHEAD_DAYS * DAY_MS))}`,
  );

  // --- Assemble ---------------------------------------------------------------------------------
  const sum = (rows: { n: number }[]) => rows.reduce((s, r) => s + Number(r.n), 0);
  const bySev = (rows: { severity: Severity; n: number }[]) => {
    const out = zeros();
    for (const r of rows) out[r.severity] += Number(r.n);
    return out;
  };
  const overdueBySeverity = zeros();
  let accepted = 0;
  let overdue = 0;
  let eol = 0;
  let kev = 0;
  for (const r of openAtEnd) {
    overdueBySeverity[r.severity] += Number(r.overdue);
    accepted += Number(r.accepted);
    overdue += Number(r.overdue);
    eol += Number(r.eol);
    kev += Number(r.kev);
  }

  const meanBySeverity = Object.fromEntries(SEVERITIES.map((s) => [s, null])) as Record<
    Severity,
    number | null
  >;
  let withSla = 0;
  let within = 0;
  let resolvedCount = 0;
  let daysTotal = 0;
  for (const r of sla) {
    withSla += Number(r.with_sla);
    within += Number(r.within);
    if (r.days !== null) {
      meanBySeverity[r.severity] = round2(Number(r.days));
      resolvedCount += Number(r.n);
      daysTotal += Number(r.days) * Number(r.n);
    }
  }

  const grades = emptyGradeDistribution();
  let scoreTotal = 0;
  const graded = scores.flatMap((r) => {
    const grade = asGrade(r.grade);
    if (!grade) return [];
    grades[grade] += 1;
    scoreTotal += Number(r.score);
    return [{ domain: { id: r.id, fqdn: r.fqdn }, score: Number(r.score), grade }];
  });
  const averageScore = graded.length > 0 ? round1(scoreTotal / graded.length) : null;
  const previousAverageScore =
    prevAvg?.avg === null || prevAvg?.avg === undefined ? null : round1(Number(prevAvg.avg));

  const report: MonthlyReport = {
    version: MONTHLY_REPORT_VERSION,
    period,
    periodStart: start.toISOString(),
    periodEnd: end.toISOString(),
    generatedAt: now.toISOString(),
    totals: {
      domains: Number(totals?.domains ?? 0),
      monitoredDomains: Number(totals?.monitored ?? 0),
      assets: Number(totals?.assets ?? 0),
      approvedAssets: Number(totals?.approved ?? 0),
      newAssets: Number(totals?.new_assets ?? 0),
    },
    findings: {
      opened: bySev(opened),
      openedTotal: sum(opened),
      reopened: Number(reopened?.n ?? 0),
      resolved: bySev(resolved),
      resolvedTotal: sum(resolved),
      openAtEnd: bySev(openAtEnd),
      openAtEndTotal: sum(openAtEnd),
      acceptedRiskAtEnd: accepted,
      overdueAtEnd: overdue,
      overdueAtEndBySeverity: overdueBySeverity,
    },
    sla: {
      policy: (await readSlaPolicy(db)).policy,
      resolvedWithSla: withSla,
      resolvedWithinSla: within,
      compliancePercent: withSla > 0 ? round1((within / withSla) * 100) : null,
      meanDaysToResolve: resolvedCount > 0 ? round2(daysTotal / resolvedCount) : null,
      meanDaysToResolveBySeverity: meanBySeverity,
    },
    topFindings: topFindings.map((r) => {
      const dueAt = r.due_at === null ? null : iso(r.due_at);
      return {
        id: r.id,
        ruleId: r.rule_id,
        title: r.title,
        severity: r.severity,
        riskScore: Number(r.risk_score),
        domain: { id: r.domain_id, fqdn: r.fqdn },
        hostname: r.hostname,
        firstSeenAt: iso(r.first_seen_at),
        dueAt,
        overdue: !r.accepted && dueAt !== null && new Date(dueAt).getTime() < end.getTime(),
      };
    }),
    topDomains: topDomains.map((r) => ({
      domain: { id: r.id, fqdn: r.fqdn },
      criticality: r.criticality,
      businessOwner: r.business_owner,
      openFindings: Number(r.open),
      riskTotal: Number(r.risk),
      highestSeverity: r.highest,
      grade: asGrade(r.grade),
    })),
    securityScore: {
      scoredDomains: graded.length,
      averageScore,
      grades,
      previousAverageScore,
      change:
        averageScore !== null && previousAverageScore !== null
          ? round1(averageScore - previousAverageScore)
          : null,
      best: graded.slice(0, BEST_WORST),
      worst: [...graded]
        .sort((a, b) => a.score - b.score || a.domain.fqdn.localeCompare(b.domain.fqdn))
        .slice(0, BEST_WORST),
    },
    exposure: {
      certificatesExpiring30d: Number(certs?.n ?? 0),
      endOfLifeSoftware: eol,
      knownExploitedSoftware: kev,
    },
  };
  // Never store something the read path would reject.
  return monthlyReportSchema.parse(report);
}

async function store(db: Database, report: MonthlyReport, now: Date, replace: boolean) {
  const values = {
    period: periodDate(report.period),
    generatedAt: now,
    data: report as unknown as Record<string, unknown>,
  };
  const q = db.insert(monthlyReports).values(values);
  const rows = replace
    ? await q
        .onConflictDoUpdate({
          target: monthlyReports.period,
          set: { generatedAt: now, data: values.data },
        })
        .returning({ id: monthlyReports.id })
    : await q.onConflictDoNothing().returning({ id: monthlyReports.id });
  return rows.length > 0;
}

/**
 * Cron step: on or after the 1st (UTC), generates the previous month's report once. Skipped when it
 * already exists, or when no domain existed before the month ended (nothing to report on).
 * Concurrent runs are harmless: the unique period index keeps the first.
 */
export async function generateDueMonthlyReport(db: Database, now: Date): Promise<number> {
  const period = previousPeriod(now);
  const [existing] = await db
    .select({ id: monthlyReports.id })
    .from(monthlyReports)
    .where(eq(monthlyReports.period, periodDate(period)));
  if (existing) return 0;
  const { end } = monthBounds(period);
  const [any] = await rowsOf<{ n: number }>(
    db,
    sql`select count(*)::int as n from domains where created_at < ${ts(end)}`,
  );
  if (!any || Number(any.n) === 0) return 0;

  return db.transaction(async (raw) => {
    const tx = raw as unknown as Database;
    const report = await buildMonthlyReport(tx, period, now);
    if (!(await store(tx, report, now, false))) return 0;
    await writeAudit(tx, {
      actorType: 'system',
      action: 'report.monthly_generated',
      resourceType: 'report',
      resourceId: period,
      metadata: { period, trigger: 'schedule' },
    });
    return 1;
  });
}

/**
 * POST /reports/monthly/generate: (re)generates `period` (default: the previous month). The current
 * month may be generated (a partial month); future months are refused. Regeneration replaces the
 * stored report. Audited `report.monthly_generated`.
 */
export async function generateMonthlyReport(
  db: Database,
  period: MonthlyPeriod | undefined,
  actor: Actor,
  now: Date,
): Promise<MonthlyReport> {
  const p = period ?? previousPeriod(now);
  if (p > periodOf(now)) {
    throw new ApiError(
      400,
      'validation_failed',
      'A report cannot be generated for a future month.',
      [{ path: 'period', message: 'The month has not started yet.' }],
    );
  }
  return db.transaction(async (raw) => {
    const tx = raw as unknown as Database;
    const [existing] = await tx
      .select({ id: monthlyReports.id })
      .from(monthlyReports)
      .where(eq(monthlyReports.period, periodDate(p)));
    const report = await buildMonthlyReport(tx, p, now);
    await store(tx, report, now, true);
    await writeAudit(tx, {
      actorType: 'user',
      actorUserId: actor.userId,
      action: 'report.monthly_generated',
      resourceType: 'report',
      resourceId: p,
      requestId: actor.requestId,
      metadata: { period: p, trigger: 'manual', regenerated: existing !== undefined },
    });
    return report;
  });
}

export async function listMonthlyReports(db: Database): Promise<MonthlyReportListResponse> {
  const rows = await db
    .select({ data: monthlyReports.data, generatedAt: monthlyReports.generatedAt })
    .from(monthlyReports)
    .orderBy(desc(monthlyReports.period));
  return {
    items: rows.flatMap((r) => {
      const parsed = monthlyReportSchema.safeParse(r.data);
      if (!parsed.success) return [];
      return [
        {
          period: parsed.data.period,
          generatedAt: r.generatedAt.toISOString(),
          openAtEndTotal: parsed.data.findings.openAtEndTotal,
          overdueAtEnd: parsed.data.findings.overdueAtEnd,
          averageScore: parsed.data.securityScore.averageScore,
        },
      ];
    }),
  };
}

export async function getMonthlyReport(
  db: Database,
  period: MonthlyPeriod,
): Promise<MonthlyReport> {
  const [row] = await db
    .select({ data: monthlyReports.data })
    .from(monthlyReports)
    .where(eq(monthlyReports.period, periodDate(period)));
  const parsed = row ? monthlyReportSchema.safeParse(row.data) : undefined;
  if (!parsed?.success) {
    throw new ApiError(404, 'not_found', 'The requested resource was not found.');
  }
  return parsed.data;
}
