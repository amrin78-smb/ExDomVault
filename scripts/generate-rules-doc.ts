/**
 * Generates docs/advisory-rules.md from the rule registry (packages/rules), so the documentation
 * can never drift from the code. Deterministic: rules sorted by id, no timestamps.
 *
 *   node scripts/generate-rules-doc.ts          write the file
 *   node scripts/generate-rules-doc.ts --check  exit 1 if the file is out of date
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as prettier from 'prettier';
import {
  CRITICALITY_FACTOR,
  DEFAULT_ADMINISTRATIVE_SERVICES,
  EXPOSURE_FACTOR,
  RISK_MODEL_VERSION,
  RULES,
  SEVERITY_WEIGHT,
  type Advisory,
  type EvaluationContext,
  type FindingCandidate,
  type Rule,
} from '../packages/rules/src/index.ts';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const target = resolve(root, 'docs/advisory-rules.md');

const APEX = 'example.com';

/** Representative finding fields per rule, so the sample advisory shows its realistic form. */
const SAMPLES: Record<string, Partial<FindingCandidate>> = {
  'DNS-001': { component: 'ns' },
  'DNS-002': {
    hostname: `shop.${APEX}`,
    component: 'cname',
    evidence: { takeoverProneService: 'azurewebsites.net' },
  },
  'DNS-003': { component: 'dmarc', evidence: { mail: 'mail' } },
  'DNS-004': {
    component: 'spf',
    evidence: { issues: [{ code: 'multiple_records' }, { code: 'pass_all' }] },
  },
  'DNS-005': { component: 'dnssec', evidence: { dnskeyPresent: false } },
  'DNS-006': { component: 'caa' },
  'DNS-007': { component: 'dmarc', evidence: { mail: 'mail', reportingConfigured: true } },
  'REG-001': { component: 'expiry' },
  'REG-002': { component: 'registrar' },
  'ASSET-001': { hostname: `dev.${APEX}`, component: `dev.${APEX}` },
  'ASSET-002': { hostname: `legacy.${APEX}`, component: 'discovery' },
};

const sampleContext: EvaluationContext = {
  now: '2026-01-01T00:00:00.000Z',
  domain: { id: 'sample', fqdn: APEX, criticality: 'high', verified: true },
  scanJobId: 'sample',
  checks: [],
  assets: [],
  administrativeServices: DEFAULT_ADMINISTRATIVE_SERVICES,
};

function sampleAdvisory(rule: Rule): Advisory | null {
  const candidate: FindingCandidate = {
    hostname: APEX,
    component: 'sample',
    title: rule.title,
    description: '',
    severity: rule.defaultSeverity,
    confidence: rule.defaultConfidence,
    exposure: 'public_record',
    evidence: {},
    ...SAMPLES[rule.id],
  };
  try {
    return rule.advisory(candidate, sampleContext);
  } catch {
    return null; // the rule needs richer evidence than this generic sample
  }
}

const cell = (s: string) => s.replace(/\|/g, '\\|').replace(/\n/g, ' ');
const list = (items: readonly string[]) =>
  items.length ? items.map((i) => `\`${i}\``).join(', ') : '—';

function renderRule(rule: Rule): string {
  const lines = [
    `### ${rule.id} — ${rule.title}`,
    '',
    '| Field | Value |',
    '| --- | --- |',
    `| Version | ${rule.version} |`,
    `| Category | \`${rule.category}\` |`,
    `| Default severity | ${rule.defaultSeverity} |`,
    `| Default confidence | ${rule.defaultConfidence} |`,
    `| Observation kinds required | ${list(rule.requires)} |`,
    `| Profile checks (any of) | ${list(rule.requiresChecks)} |`,
    '',
    `**Evidence required.** ${rule.evidenceRequirements}`,
    '',
    `**Detection.** ${rule.detection}`,
    '',
    `**Resolution.** ${rule.resolution}`,
    '',
  ];
  const advisory = sampleAdvisory(rule);
  if (advisory) {
    lines.push(
      `**Sample advisory** (for \`${SAMPLES[rule.id]?.hostname ?? APEX}\`): _${advisory.title}_`,
      '',
      `${advisory.summary} ${advisory.businessImpact}`,
      '',
      'Recommended actions:',
      '',
      ...advisory.recommendedActions.map((a) => `- ${a}`),
      '',
      'References:',
      '',
      ...advisory.references.map((r) => `- <${r}>`),
      '',
    );
  }
  return lines.join('\n');
}

async function render(): Promise<string> {
  const rules = [...RULES].sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));
  const out = [
    '# Advisory rules',
    '',
    '<!-- Generated by scripts/generate-rules-doc.ts from packages/rules. Do not edit by hand: run `npm run rules:docs`. -->',
    '',
    'Deterministic, versioned rules turn the observations of a successful scan job into findings',
    '(design §8). Severity and confidence come only from rule code — never from an LLM. An observation',
    'is not a vulnerability: rule text states what was observed and why it matters, and never claims',
    'compromise. A rule runs only when the job profile includes one of its checks and the job produced',
    'successful observations of every kind it requires; failed, timed-out, partial or missing evidence',
    'neither raises nor resolves a finding. A finding resolves only when its rule evaluated the same',
    'component with successful evidence and the condition was absent.',
    '',
    `## Risk model ${RISK_MODEL_VERSION}`,
    '',
    '`risk_score = clamp(round(severity_weight × exposure_factor × criticality_factor), 0, 100)`.',
    'Severity stays separate from the risk score; the inputs are stored with every finding.',
    '',
    '| Severity | Weight |',
    '| --- | --- |',
    ...Object.entries(SEVERITY_WEIGHT).map(([k, v]) => `| ${k} | ${v} |`),
    '',
    '| Exposure | Factor |',
    '| --- | --- |',
    ...Object.entries(EXPOSURE_FACTOR).map(([k, v]) => `| \`${k}\` | ${v} |`),
    '',
    '| Domain criticality | Factor |',
    '| --- | --- |',
    ...Object.entries(CRITICALITY_FACTOR).map(([k, v]) => `| ${k} | ${v} |`),
    '',
    '## Default exposure policy',
    '',
    'Administrative and data services that should not be reachable from the internet (used by the',
    'exposure rules). Exceptions are handled as accepted risk.',
    '',
    '| Port | Service | Severity |',
    '| --- | --- | --- |',
    ...[...DEFAULT_ADMINISTRATIVE_SERVICES]
      .sort((a, b) => a.port - b.port)
      .map((s) => `| ${s.port} | ${cell(s.service)} | ${s.severity} |`),
    '',
    '## Rules',
    '',
    '| ID | Version | Category | Title | Default severity | Default confidence |',
    '| --- | --- | --- | --- | --- | --- |',
    ...rules.map(
      (r) =>
        `| [${r.id}](#${r.id.toLowerCase()}--${r.title
          .toLowerCase()
          .replace(/[^a-z0-9 -]/g, '')
          .replace(
            / /g,
            '-',
          )}) | ${r.version} | ${r.category} | ${cell(r.title)} | ${r.defaultSeverity} | ${r.defaultConfidence} |`,
    ),
    '',
    ...rules.map(renderRule),
  ].join('\n');
  const config = (await prettier.resolveConfig(target)) ?? {};
  return prettier.format(out, { ...config, filepath: target });
}

const content = await render();
if (process.argv.includes('--check')) {
  let existing = '';
  try {
    existing = readFileSync(target, 'utf8');
  } catch {
    // missing file is out of date
  }
  if (existing !== content) {
    console.error('docs/advisory-rules.md is out of date: run `npm run rules:docs`.');
    process.exit(1);
  }
  console.log('docs/advisory-rules.md is up to date.');
} else {
  writeFileSync(target, content);
  console.log(`Wrote docs/advisory-rules.md (${RULES.length} rules).`);
}
